#!/usr/bin/env node
// Bake the camera's Japanese type into firmware/p4/main/ui_font_jp.h.
//
//   npm run font:jp:bake          fetch, verify, regenerate
//   npm run font:jp:check         regenerate into memory and diff; fail on drift
//
// The face is Shinonome 16 (東雲フォント), the /efont/ bitmap gothic: the
// whole of JIS X 0208 at 16x16 plus the 8x16 half-width set, drawn by hand
// in 2000-2001 and released into the public domain. It is the type of the
// era this camera's screen belongs to, and a bitmap face is the only kind
// that survives being drawn by a firmware with no font engine: every glyph
// is 32 bytes of pixels, scaled by whole numbers on the device, and nothing
// is ever resampled.
//
// The sources are the project's own .bit files: BDF with the bitmap rows
// written as character art ('@' 'p' 'P' 'O' 'o' are ink, per tools/bit2bdf).
// Encodings are JIS X 0208 row/cell for the kanji file and Latin-1 / JIS X
// 0201 for the half-width ones; they are mapped to Unicode here so ui.c can
// look glyphs up straight from UTF-8 string literals.
//
// Pinned by commit and by digest, like the icons: a font that changes under
// the build would move every label on the camera without anything failing.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'firmware/p4/main/ui_font_jp.h');
const CACHE = join(ROOT, 'node_modules/.cache/shinonome');

const SRC = { repo: 'code4fukui/shinonome-font', commit: '053b21e0a11ef5799c1ea3cefc374763add80617' };
const FILES = [
  { key: 'kanji', path: '16/kanjic/font_src.bit', sha256: '38ed485b3565b9c71147a459a9d0f8057714948ca6eaa2e6a3d74c95868d6467' },
  { key: 'latin', path: '16/latin1/font_src.bit', sha256: 'dbc6362567edb4e2de7041ad03864f848b1cfbe7c966aba89bb34d0068bd896d' },
  { key: 'hankaku', path: '16/hankaku/font_src_diff.bit', sha256: '0f8603843a64cf9775a32d70e14f5fd05b0047cd4ae278966f9a41ec770ef376' },
];

async function fetchFile(f) {
  const cached = join(CACHE, `${SRC.commit.slice(0, 12)}-${f.path.replace(/\//g, '-')}`);
  let buf;
  try {
    buf = readFileSync(cached);
  } catch {
    const url = `https://cdn.jsdelivr.net/gh/${SRC.repo}@${SRC.commit}/${f.path}`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${f.path}: HTTP ${res.status} from ${url}`);
    buf = Buffer.from(await res.arrayBuffer());
    mkdirSync(CACHE, { recursive: true });
    writeFileSync(cached, buf);
  }
  const got = createHash('sha256').update(buf).digest('hex');
  if (got !== f.sha256) {
    throw new Error(`${f.path}: sha256 ${got}, expected ${f.sha256}. Delete node_modules/.cache/shinonome to re-fetch, or update the digest deliberately.`);
  }
  return buf.toString('latin1');
}

/** Every glyph in a .bit file: { enc, w, h, rows: number[] } with rows as bit masks, MSB = left. */
function parseBit(text) {
  const out = [];
  let cur = null, inBitmap = false;
  for (const raw of text.split('\n')) {
    const line = raw.replace(/\r$/, '');
    if (line.startsWith('STARTCHAR')) { cur = { enc: -1, w: 0, h: 0, rows: [] }; inBitmap = false; continue; }
    if (!cur) continue;
    if (line.startsWith('ENCODING')) { cur.enc = parseInt(line.split(/\s+/)[1], 10); continue; }
    if (line.startsWith('BBX')) { const p = line.split(/\s+/); cur.w = +p[1]; cur.h = +p[2]; continue; }
    if (line.startsWith('BITMAP')) { inBitmap = true; continue; }
    if (line.startsWith('ENDCHAR')) { out.push(cur); cur = null; inBitmap = false; continue; }
    if (inBitmap) {
      const body = line.replace(/\s*#.*$/, '');
      let mask = 0;
      for (let i = 0; i < body.length; i++) mask = (mask << 1) | ('pPOo@'.includes(body[i]) ? 1 : 0);
      cur.rows.push(mask << (Math.max(0, (cur.w || body.length) - body.length)));
    }
  }
  return out;
}

const jis = new TextDecoder('iso-2022-jp');
function jisToUnicode(code) {
  const hi = code >> 8, lo = code & 0xff;
  const s = jis.decode(Uint8Array.from([0x1b, 0x24, 0x42, hi, lo, 0x1b, 0x28, 0x42]));
  const cp = s.codePointAt(0);
  return s.length === 1 && cp !== 0xfffd ? cp : -1;
}

function emit(full, half) {
  const L = [];
  L.push('// Generated by tools/mkfont-shinonome.mjs. Do not edit by hand.');
  L.push('//');
  L.push('// Shinonome 16 (東雲フォント): the /efont/ bitmap gothic, JIS X 0208 at 16x16 and');
  L.push('// the 8x16 half-width set, mapped to Unicode. Public domain (see');
  L.push('// THIRD_PARTY_NOTICES.md). Glyphs are 1 bit per pixel, MSB first, one row per');
  L.push('// two bytes (full width) or one byte (half width); the baseline sits');
  L.push('// JP16_DESCENT rows above the cell bottom.');
  L.push(`// Source: https://github.com/${SRC.repo} @ ${SRC.commit}`);
  L.push('#pragma once');
  L.push('#include <stdint.h>');
  L.push('');
  L.push('#define JP16_CELL 16');
  L.push('#define JP16_DESCENT 2');
  L.push(`#define JP16_COUNT ${full.length}`);
  L.push(`#define HW16_COUNT ${half.length}`);
  L.push('');
  const cps = (arr) => { const o = []; for (let i = 0; i < arr.length; i += 16) o.push('    ' + arr.slice(i, i + 16).map((g) => '0x' + g.cp.toString(16).padStart(4, '0')).join(', ') + ','); return o; };
  L.push('/* Codepoints, ascending, so a glyph is a binary search away. */');
  L.push(`static const uint16_t JP16_CP[JP16_COUNT] = {`); L.push(...cps(full)); L.push('};');
  L.push(`static const uint16_t HW16_CP[HW16_COUNT] = {`); L.push(...cps(half)); L.push('};');
  L.push('');
  L.push('/* 16 rows of 16 bits each. */');
  L.push('static const uint8_t JP16_BITS[JP16_COUNT][32] = {');
  for (const g of full) {
    const b = [];
    for (let r = 0; r < 16; r++) { const m = g.rows[r] ?? 0; b.push((m >> 8) & 0xff, m & 0xff); }
    L.push('    {' + b.map((v) => '0x' + v.toString(16).padStart(2, '0')).join(',') + '}, /* U+' + g.cp.toString(16).padStart(4, '0') + ' */');
  }
  L.push('};');
  L.push('/* 16 rows of 8 bits each. */');
  L.push('static const uint8_t HW16_BITS[HW16_COUNT][16] = {');
  for (const g of half) {
    const b = [];
    for (let r = 0; r < 16; r++) b.push((g.rows[r] ?? 0) & 0xff);
    L.push('    {' + b.map((v) => '0x' + v.toString(16).padStart(2, '0')).join(',') + '}, /* U+' + g.cp.toString(16).padStart(4, '0') + ' */');
  }
  L.push('};');
  L.push('');
  return L.join('\n');
}

async function main() {
  const check = process.argv.includes('--check');
  const src = {};
  for (const f of FILES) src[f.key] = parseBit(await fetchFile(f));

  const full = [];
  const seen = new Set();
  for (const g of src.kanji) {
    if (g.rows.length !== 16) continue;
    const cp = jisToUnicode(g.enc);
    if (cp < 0 || cp > 0xffff || seen.has(cp)) continue;
    seen.add(cp);
    full.push({ cp, rows: g.rows });
  }
  full.sort((a, b) => a.cp - b.cp);

  const halfMap = new Map();
  for (const g of src.latin) if (g.enc >= 0x20 && g.enc <= 0xff && g.rows.length === 16) halfMap.set(g.enc, g.rows);
  /* JIS X 0201: the katakana half live at U+FF61.., and the yen/overline
   * variants of 0x5C/0x7E are kept as ASCII so a path or a tilde still reads. */
  for (const g of src.hankaku) {
    if (g.rows.length !== 16) continue;
    if (g.enc >= 0xa1 && g.enc <= 0xdf) halfMap.set(0xff61 + (g.enc - 0xa1), g.rows);
  }
  const half = [...halfMap.entries()].map(([cp, rows]) => ({ cp, rows })).sort((a, b) => a.cp - b.cp);

  const text = emit(full, half);
  process.stdout.write(`shinonome 16: ${full.length} full-width glyphs, ${half.length} half-width\n`);
  if (check) {
    const have = readFileSync(OUT, 'utf8');
    if (have !== text) { console.error(`\n${OUT} is stale. Run: npm run font:jp:bake`); process.exit(1); }
    console.log('ui_font_jp.h is current.');
    return;
  }
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${(text.length / 1024).toFixed(0)} KB)`);
}

main().catch((e) => { console.error(e.message); process.exit(1); });
