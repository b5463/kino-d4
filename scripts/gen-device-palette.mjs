#!/usr/bin/env node
// The camera's on-glass palette, from one JSON file to one C header.
//
//   npm run palette:gen      write firmware/p4/main/ui_palette.h from
//                            packages/design-system/kino-device-palette.json
//   npm run palette:check    fail when the committed header is not what the
//                            JSON generates
//
// The JSON is the only place a device colour is written down. ui_theme.h
// includes the generated header and adds what is not a value: RGB(), the type
// roles and the pairs the theme test measures. ui.c asks for colours by role
// name only.
//
// Three sections:
//   colours  one sRGB value per name. No two may pack to the same RGB565 code:
//            two names for one value is a role, not a second colour.
//   roles    a name for what a colour is used for, pointing at a colour. A
//            role changes meaning by pointing somewhere else, not by holding a
//            second copy of a value.
//   arrays   ordered tables: `values` for one row, `rows` for several of equal
//            width. Emitted as static const tables, so they live in flash.
//
// The header keeps the line endings of the copy on disk (CRLF in a Windows
// checkout, LF in CI's) and is CRLF when it does not exist yet. The check
// compares with line endings normalised, so it holds on both.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'packages', 'design-system', 'kino-device-palette.json');
const OUT = join(root, 'firmware', 'p4', 'main', 'ui_palette.h');
const rel = (p) => relative(root, p).split('\\').join('/');

const NAME = /^K_[A-Z0-9_]+$/;
const HEX = /^[0-9a-f]{6}$/;
const WRAP = 80;

function fail(msg) {
  console.error(`[palette] ${msg}`);
  process.exit(1);
}

function rgb(hex, where) {
  if (typeof hex !== 'string' || !HEX.test(hex)) fail(`${where}: "${hex}" is not six lower-case hex digits`);
  return [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16));
}

/** The panel's code for a colour, packed exactly as ui_theme.h's RGB() packs it. */
function pack565([r, g, b]) {
  return ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3);
}

const hex2 = (v) => `0x${v.toString(16).padStart(2, '0')}`;
const hex4 = (v) => `0x${v.toString(16).toUpperCase().padStart(4, '0')}`;
const rgbCall = (hex, where) => `RGB(${rgb(hex, where).map(hex2).join(', ')})`;

/** A C comment of `text`, wrapped to WRAP columns at `indent`. */
function comment(text, indent = '') {
  if (typeof text !== 'string' || text.trim() === '') return [];
  const words = text.trim().split(/\s+/);
  const width = WRAP - indent.length - 3;
  const lines = [];
  let line = '';
  for (const w of words) {
    if (line && line.length + 1 + w.length > width) {
      lines.push(line);
      line = w;
    } else line = line ? `${line} ${w}` : w;
  }
  lines.push(line);
  if (lines.length === 1 && lines[0].length + 6 <= WRAP - indent.length) return [`${indent}/* ${lines[0]} */`];
  return lines.map((l, i) => `${indent}${i === 0 ? '/* ' : ' * '}${l}`).concat(`${indent} */`);
}

function generate(spec) {
  const names = new Set();
  const claim = (name, where) => {
    if (!NAME.test(name)) fail(`${where}: "${name}" is not a K_* name`);
    if (names.has(name)) fail(`${where}: "${name}" is defined twice`);
    names.add(name);
  };

  const out = [
    `// Generated by scripts/gen-device-palette.mjs from`,
    `// ${rel(SRC)}. Do not edit by hand:`,
    `// edit the JSON, then run \`npm run palette:gen\`. \`npm run palette:check\``,
    `// fails when this file is not what the JSON generates.`,
    `//`,
    `// Included by ui_theme.h, which defines RGB(). Values are sRGB; the comment`,
    `// after each is the RGB565 code the panel is sent.`,
    `#pragma once`,
    `#include <stdint.h>`,
    ``,
    `#ifndef RGB`,
    `#error "include ui_theme.h, not ui_palette.h: RGB() is defined there"`,
    `#endif`,
    ``,
    `/* Colours. */`,
  ];

  const colours = spec.colours ?? {};
  if (Object.keys(colours).length === 0) fail('colours: empty');
  const codes = new Map();
  for (const [name, c] of Object.entries(colours)) {
    claim(name, 'colours');
    const code = pack565(rgb(c?.hex, `colours.${name}`));
    if (codes.has(code)) {
      fail(`colours.${name} packs to ${hex4(code)}, the same code as ${codes.get(code)}: make it a role`);
    }
    codes.set(code, name);
    out.push(...comment(c.note));
    out.push(`#define ${name} ${rgbCall(c.hex, `colours.${name}`)} /* ${hex4(code)} */`);
  }

  const roles = spec.roles ?? {};
  if (Object.keys(roles).length > 0) {
    out.push('', '/* Roles: what a colour is used for. Each is one of the colours above. */');
    for (const [name, r] of Object.entries(roles)) {
      claim(name, 'roles');
      if (!Object.hasOwn(colours, r?.is)) fail(`roles.${name}: "${r?.is}" is not a colour`);
      out.push(...comment(r.note));
      out.push(`#define ${name} ${r.is}`);
    }
  }

  const arrays = spec.arrays ?? {};
  for (const [name, a] of Object.entries(arrays)) {
    claim(name, 'arrays');
    claim(`${name}_N`, 'arrays');
    out.push('');
    out.push(...comment(a.note));
    if (Array.isArray(a.values)) {
      if (a.values.length === 0) fail(`arrays.${name}: no values`);
      const calls = a.values.map((h, i) => rgbCall(h, `arrays.${name}[${i}]`));
      out.push(`#define ${name}_N ${calls.length}`);
      out.push(`static const uint16_t ${name}[${name}_N] = {`);
      const per = calls.length % 4 === 0 ? 4 : 3;
      for (let i = 0; i < calls.length; i += per) out.push(`    ${calls.slice(i, i + per).join(', ')},`);
      out.push('};');
    } else if (Array.isArray(a.rows)) {
      if (a.rows.length === 0) fail(`arrays.${name}: no rows`);
      const width = a.rows[0]?.values?.length ?? 0;
      if (width === 0) fail(`arrays.${name}.rows[0]: no values`);
      claim(`${name}_W`, 'arrays');
      out.push(`#define ${name}_N ${a.rows.length}`);
      out.push(`#define ${name}_W ${width}`);
      out.push(`static const uint16_t ${name}[${name}_N][${name}_W] = {`);
      a.rows.forEach((row, ri) => {
        if (!Array.isArray(row?.values) || row.values.length !== width) {
          fail(`arrays.${name}.rows[${ri}]: needs ${width} values, like rows[0]`);
        }
        out.push(...comment(row.note, '    '));
        out.push(`    {${row.values.map((h, i) => rgbCall(h, `arrays.${name}.rows[${ri}][${i}]`)).join(', ')}},`);
      });
      out.push('};');
    } else fail(`arrays.${name}: needs "values" or "rows"`);
  }
  return out.join('\n') + '\n';
}

let spec;
try {
  spec = JSON.parse(readFileSync(SRC, 'utf8'));
} catch (e) {
  fail(`${rel(SRC)}: ${e.message}`);
}
const want = generate(spec);
const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;

if (process.argv.includes('--check')) {
  if (have === null) fail(`${rel(OUT)} is missing. Run: npm run palette:gen`);
  if (have.replace(/\r\n/g, '\n') !== want) fail(`${rel(OUT)} is stale against ${rel(SRC)}. Run: npm run palette:gen`);
  console.log(`[palette] ${rel(OUT)} matches ${rel(SRC)}`);
} else {
  const crlf = have === null || have.includes('\r\n');
  writeFileSync(OUT, crlf ? want.replace(/\n/g, '\r\n') : want);
  console.log(`[palette] wrote ${rel(OUT)}`);
}
